// Helper to retrieve placements based on apparel piece
export const getApparelPlacements = (apparelType: ApparelType = 'tshirt'): PrintPlacementZone[] => {
  switch (apparelType) {
    case 'hoodie':
      return HOODIE_PRINT_PLACEMENTS;
    case 'pants':
      return PANTS_PRINT_PLACEMENTS;
    case 'beanie':
      return BEANIE_PRINT_PLACEMENTS;
    case 'socks':
      return SOCKS_PRINT_PLACEMENTS;
    case 'tshirt':
    default:
      return DEFAULT_PRINT_PLACEMENTS;
  }
};

